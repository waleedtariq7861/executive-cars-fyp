const express = require('express')
const router = express.Router()
const protect = require('../middleware/auth')
const memberAccountOnly = require('../middleware/memberAccountOnly')
const adminOnly = require('../middleware/adminOnly')
const { loginLimiter, adminLoginLimiter, registerLimiter, forgotPasswordLimiter, resetPasswordLimiter, emailVerificationLimiter, mfaLimiter } = require('../middleware/rateLimits')
const { adminLogin, accountRegister, accountLogin, changePassword, session, logout } = require('../controllers/authController')
const { requestPasswordReset, resetPassword } = require('../controllers/passwordResetController')
const { sendCode, verifyCode } = require('../controllers/emailVerificationController')
const { listSessions, revokeOneSession, revokeOtherSessions, listActivity } = require('../controllers/securityController')
const mfa = require('../controllers/mfaController')

router.post('/admin/login',     adminLoginLimiter, adminLogin)
router.post('/admin/login/mfa', adminLoginLimiter, mfa.completeAdminLogin)
router.post('/register',        registerLimiter, accountRegister)
router.post('/login',           loginLimiter, accountLogin)
router.post('/change-password', protect, changePassword)
router.get('/session',             protect, session)
router.post('/logout',             logout)
router.get('/sessions',                   protect, listSessions)
router.post('/sessions/revoke-others',    protect, revokeOtherSessions)
router.delete('/sessions/:id',            protect, revokeOneSession)
router.get('/activity',                   protect, listActivity)
router.get('/mfa',                        protect, adminOnly, mfa.status)
router.post('/mfa/setup',                 protect, adminOnly, mfaLimiter, mfa.setup)
router.post('/mfa/enable',                protect, adminOnly, mfaLimiter, mfa.enable)
router.post('/mfa/disable',               protect, adminOnly, mfaLimiter, mfa.disable)
router.post('/mfa/recovery-codes',        protect, adminOnly, mfaLimiter, mfa.regenerateRecoveryCodes)
router.post('/email/send-code', protect, memberAccountOnly, emailVerificationLimiter, sendCode)
router.post('/email/verify',    protect, memberAccountOnly, emailVerificationLimiter, verifyCode)
router.post('/forgot-password', forgotPasswordLimiter, requestPasswordReset)
router.post('/reset-password',  resetPasswordLimiter, resetPassword)

module.exports = router
